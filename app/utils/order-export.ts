import type { OrderDetail } from "~/types/admin/orders";

// Invoice downloads for one requisition. The libraries are imported on demand so they
// only load when someone actually exports. Client only.

const money = (n: number) =>
  `EGP ${n.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

const fileName = (d: OrderDetail, ext: string) =>
  `invoice-${d.row.id.slice(1).toLowerCase()}.${ext}`;

/** Invoice as a PDF: header, customer, line items and the price breakdown. */
export const downloadOrderPdf = async (d: OrderDetail) => {
  const [{ jsPDF }, { autoTable }] = await Promise.all([
    import("jspdf"),
    import("jspdf-autotable"),
  ]);

  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const margin = 40;
  const accent: [number, number, number] = [196, 36, 18];

  doc
    .setFont("helvetica", "bold")
    .setFontSize(20)
    .text(`Requisition ${d.row.id}`, margin, 56);
  doc.setFont("helvetica", "normal").setFontSize(10).setTextColor(110);
  doc.text(
    `Created ${d.row.placedAt.slice(0, 10)} ${d.row.placedAt.slice(11, 19)} UTC  |  Hash ${d.row.hex}`,
    margin,
    74,
  );

  doc
    .setTextColor(30)
    .setFontSize(11)
    .setFont("helvetica", "bold")
    .text("Customer", margin, 104);
  doc.setFont("helvetica", "normal").setFontSize(10);
  doc.text(
    [
      d.row.customer.name,
      d.row.customer.org,
      d.customer.email,
      d.customer.phone,
      `Tax ID: ${d.customer.taxId}`,
    ],
    margin,
    120,
  );

  const phase = d.phases.find((p) => p.stage === d.row.stage);
  doc.setFont("helvetica", "bold").setFontSize(11).text("Status", 340, 104);
  doc.setFont("helvetica", "normal").setFontSize(10);
  doc.text(
    [
      `Stage: ${phase?.title ?? d.row.stage}`,
      `Waybill: ${d.shipment.waybill}`,
      `Carrier: ${d.shipment.carrier}`,
    ],
    340,
    120,
  );

  autoTable(doc, {
    startY: 205,
    margin: { left: margin, right: margin },
    head: [["SKU", "Item", "Qty", "Unit price", "Total"]],
    body: d.lines.map((l) => [
      l.sku,
      `${l.title}\n${l.spec}`,
      `${l.quantity} ${l.unit}${l.quantity > 1 ? "s" : ""}`,
      money(l.unitPrice),
      money(l.total),
    ]),
    headStyles: { fillColor: accent },
    styles: { fontSize: 9, cellPadding: 6, valign: "middle" },
    columnStyles: {
      2: { halign: "right" },
      3: { halign: "right" },
      4: { halign: "right" },
    },
  });

  const p = d.pricing;
  const totals: [string, string][] = [
    ["Subtotal allocated substrates", money(p.subtotal)],
    ["Cleanroom QA & spectro-profiling fee", money(p.qaFee)],
    ["Armored courier climate transit", money(p.courier)],
    ...(p.discount
      ? ([
          [
            `Institutional discount (-${Math.round(p.discountRate * 100)}%)`,
            `-${money(p.discount)}`,
          ],
        ] as [string, string][])
      : []),
    ["Value added tax (19%)", money(p.vat)],
    ["Total escrow requisition value", money(p.total)],
  ];

  const afterLines =
    (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable
      ?.finalY ?? 400;
  autoTable(doc, {
    startY: afterLines + 16,
    margin: { left: 300, right: margin },
    body: totals,
    theme: "plain",
    styles: { fontSize: 9, cellPadding: 4 },
    columnStyles: { 1: { halign: "right" } },
    didParseCell: (hook) => {
      if (hook.row.index === totals.length - 1) {
        hook.cell.styles.fontStyle = "bold";
        hook.cell.styles.fontSize = 11;
      }
    },
  });

  doc.setFontSize(8).setTextColor(130);
  doc.text(
    "Generated by PrintPro admin. Escrow values are held in the vault until release.",
    margin,
    doc.internal.pageSize.getHeight() - 30,
  );

  doc.save(fileName(d, "pdf"));
};

/** Invoice as a workbook: summary, line items, internal notes and the ledger. */
export const downloadOrderExcel = async (d: OrderDetail) => {
  const XLSX = await import("xlsx");
  const p = d.pricing;

  const book = XLSX.utils.book_new();
  const add = (name: string, rows: (string | number)[][], widths: number[]) => {
    const sheet = XLSX.utils.aoa_to_sheet(rows);
    sheet["!cols"] = widths.map((wch) => ({ wch }));
    XLSX.utils.book_append_sheet(book, sheet, name);
  };

  add(
    "Summary",
    [
      ["Requisition", d.row.id],
      ["Created (UTC)", d.row.placedAt],
      ["Hash", d.row.hex],
      ["Customer", d.row.customer.name],
      ["Atelier", d.row.customer.org],
      ["Email", d.customer.email],
      ["Stage", d.row.stage],
      ["Waybill", d.shipment.waybill],
      [],
      ["Subtotal (EGP)", p.subtotal],
      ["Cleanroom QA fee (EGP)", p.qaFee],
      ["Armored courier (EGP)", p.courier],
      ["Institutional discount (EGP)", -p.discount],
      ["VAT 19% (EGP)", p.vat],
      ["Total escrow value (EGP)", p.total],
    ],
    [30, 44],
  );

  add(
    "Line items",
    [
      ["SKU", "Item", "Spec", "Qty", "Unit", "Unit price (EGP)", "Total (EGP)"],
      ...d.lines.map((l) => [
        l.sku,
        l.title,
        l.spec,
        l.quantity,
        l.unit,
        l.unitPrice,
        l.total,
      ]),
    ],
    [20, 44, 40, 6, 8, 16, 14],
  );

  add(
    "Notes",
    [
      ["Author", "When", "Urgent", "Note"],
      ...d.notes.map((n) => [n.author, n.ago, n.urgent ? "Yes" : "No", n.text]),
    ],
    [28, 14, 8, 90],
  );

  add(
    "Ledger",
    [["Timestamp (UTC)", "Event"], ...d.ledger.map((e) => [e.at, e.text])],
    [26, 70],
  );

  XLSX.writeFile(book, fileName(d, "xlsx"));
};