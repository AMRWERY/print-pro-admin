import { cohortLabel, funnelLabel, pointLabel, regionLabel, velocityMeta } from "~/data/analytics-meta";
import { categoryMeta } from "~/data/product-meta";
import type { AnalyticsResponse, TopProductRow } from "~/types/admin/analytics";

// The analytics report as a PDF or an Excel workbook. The libraries load on demand. Client only.

const egp = (n: number) =>
  `EGP ${n.toLocaleString("en-US", { minimumFractionDigits: 0, maximumFractionDigits: 0 })}`;
const pct = (n: number, d = 1) => `${n.toFixed(d)}%`;

const fileStamp = (a: AnalyticsResponse) => `${a.period.from}_${a.period.to}`;

const subtitle = (a: AnalyticsResponse) =>
  `${a.period.from} to ${a.period.to} (${a.period.days} day${a.period.days > 1 ? "s" : ""}) · ${cohortLabel[a.query.cohort]}`;

export const downloadAnalyticsPdf = async (a: AnalyticsResponse, top: TopProductRow[]) => {
  const [{ jsPDF }, { autoTable }] = await Promise.all([import("jspdf"), import("jspdf-autotable")]);

  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const margin = 40;
  const accent: [number, number, number] = [196, 36, 18];
  const after = () => (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? 100;
  const table = (head: string[], body: (string | number)[][], right: number[] = []) =>
    autoTable(doc, {
      startY: after() + 18,
      margin: { left: margin, right: margin },
      head: [head],
      body: body.map((r) => r.map(String)),
      headStyles: { fillColor: accent },
      styles: { fontSize: 8.5, cellPadding: 4 },
      columnStyles: Object.fromEntries(right.map((i) => [i, { halign: "right" as const }])),
    });

  doc.setFont("helvetica", "bold").setFontSize(18).text("Commercial telemetry & yield analytics", margin, 52);
  doc.setFont("helvetica", "normal").setFontSize(9).setTextColor(110).text(subtitle(a), margin, 68);

  const k = a.kpis;
  autoTable(doc, {
    startY: 84,
    margin: { left: margin, right: margin },
    head: [["Indicator", "Value", "Change"]],
    body: [
      ["Gross turnover", egp(k.turnover), `${k.turnoverDelta >= 0 ? "+" : ""}${pct(k.turnoverDelta)} vs previous period`],
      ["Orders & requisitions", String(k.orders), `+${pct(k.ordersDelta)} (${k.inCustody} in custody)`],
      ["Average order value", egp(k.aov), `+${pct(k.aovDelta)}`],
      ["Storefront conversion", pct(k.conversion, 2), `+${pct(k.conversionDelta, 2)} (${k.sessions} sessions)`],
      ["Verified studio intake", `+${k.intake}`, `+${pct(k.intakeDelta)}`],
    ],
    headStyles: { fillColor: accent },
    styles: { fontSize: 9, cellPadding: 5 },
  });

  table(
    ["Funnel stage", "Count", "Of sessions", "Drop-off"],
    a.funnel.stages.map((s) => [funnelLabel[s.key].title, s.count, pct(s.pct, 2), s.drop === null ? "-" : pct(s.drop)]),
    [1, 2, 3],
  );
  table(
    ["Division", "Revenue", "Share", "YoY", "Margin"],
    a.categories.map((c) => [categoryMeta[c.category].label, egp(c.revenue), pct(c.share), pct(c.yoy), pct(c.margin)]),
    [1, 2, 3, 4],
  );
  table(
    ["Region", "Requisitions", "Revenue", "Share"],
    a.regions.map((r) => [regionLabel[r.key].name, r.orders, egp(r.revenue), pct(r.share)]),
    [1, 2, 3],
  );
  table(
    ["Best-selling apparatus", "Units", "Revenue", "Margin", "Buffer", "Status"],
    top.map((t) => [`${t.name} (${t.sku})`, t.units, egp(t.revenue), pct(t.margin), `${t.daysLeft} days`, velocityMeta[t.status].label]),
    [1, 2, 3, 4],
  );

  doc.setFontSize(8).setTextColor(130);
  doc.text("Generated by PrintPro admin. Demo figures.", margin, doc.internal.pageSize.getHeight() - 30);
  doc.save(`analytics-report-${fileStamp(a)}.pdf`);
};

export const downloadAnalyticsExcel = async (a: AnalyticsResponse, top: TopProductRow[]) => {
  const XLSX = await import("xlsx");
  const book = XLSX.utils.book_new();
  const add = (name: string, rows: (string | number)[][], widths: number[]) => {
    const sheet = XLSX.utils.aoa_to_sheet(rows);
    sheet["!cols"] = widths.map((wch) => ({ wch }));
    XLSX.utils.book_append_sheet(book, sheet, name);
  };
  const k = a.kpis;

  add(
    "Summary",
    [
      ["Period", `${a.period.from} to ${a.period.to}`],
      ["Previous period", `${a.period.prevFrom} to ${a.period.prevTo}`],
      ["Cohort", cohortLabel[a.query.cohort]],
      [],
      ["Gross turnover", k.turnover],
      ["Change vs previous period (%)", k.turnoverDelta],
      ["Orders and requisitions", k.orders],
      ["In custody", k.inCustody],
      ["Average order value", k.aov],
      ["Storefront conversion (%)", k.conversion],
      ["Sessions", k.sessions],
      ["Verified studio intake", k.intake],
      ["Portfolio weighted margin (%)", a.portfolioMargin],
    ],
    [34, 30],
  );
  add(
    "Revenue",
    [["Interval", "Revenue", "Previous period", "Escrow release", "Net margin"], ...a.series.map((p) => [pointLabel(p.at, a.granularity), p.revenue, p.prior, p.escrow, p.margin])],
    [16, 14, 16, 16, 14],
  );
  add(
    "Funnel",
    [["Stage", "Count", "Share of sessions (%)", "Drop-off (%)"], ...a.funnel.stages.map((s) => [funnelLabel[s.key].title, s.count, s.pct, s.drop ?? ""])],
    [34, 12, 22, 14],
  );
  add(
    "Divisions",
    [["Division", "Revenue", "Share (%)", "YoY (%)", "Margin (%)"], ...a.categories.map((c) => [categoryMeta[c.category].label, c.revenue, c.share, c.yoy, c.margin])],
    [30, 14, 12, 10, 12],
  );
  add(
    "Regions",
    [["Region", "Requisitions", "Revenue", "Share (%)"], ...a.regions.map((r) => [regionLabel[r.key].name, r.orders, r.revenue, r.share])],
    [30, 14, 14, 12],
  );
  add(
    "Best sellers",
    [["Rank", "SKU", "Name", "Division", "Units", "Revenue", "Margin (%)", "Days of buffer", "Status"], ...top.map((t) => [t.rank, t.sku, t.name, categoryMeta[t.category].label, t.units, t.revenue, t.margin, t.daysLeft, velocityMeta[t.status].label])],
    [6, 18, 40, 24, 8, 14, 10, 14, 12],
  );

  XLSX.writeFile(book, `analytics-report-${fileStamp(a)}.xlsx`);
};
