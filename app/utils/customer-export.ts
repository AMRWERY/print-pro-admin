import type { CustomerDetail } from "~/types/admin/customers";

// Printable client dossier as a PDF. The libraries load on demand. Client only.

const egp = (n: number) =>
  `EGP ${n.toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

export const downloadCustomerPdf = async (c: CustomerDetail) => {
  const [{ jsPDF }, { autoTable }] = await Promise.all([import("jspdf"), import("jspdf-autotable")]);

  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const margin = 40;
  const accent: [number, number, number] = [196, 36, 18];
  const after = () => (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? 120;

  doc.setFont("helvetica", "bold").setFontSize(20).text(c.name, margin, 56);
  doc.setFont("helvetica", "normal").setFontSize(10).setTextColor(110);
  doc.text(`${c.role}  |  ${c.org}`, margin, 74);
  doc.text(`Client ${c.id}  |  Tier ${c.tier}  |  Status ${c.status}`, margin, 90);

  autoTable(doc, {
    startY: 110,
    margin: { left: margin, right: margin },
    theme: "grid",
    head: [["Account", ""]],
    body: [
      ["Lifetime value", egp(c.ltv)],
      ["Completed orders", String(c.orders)],
      ["Active open orders", String(c.activeOrders)],
      ["On-time payment rating", `${c.paymentRating}%`],
      ["Email", c.email],
      ["Direct line", c.phone || "-"],
      ["Region", c.node],
      ["Delivery address", c.deliveryAddress || "-"],
      ["Tax / legal ID", c.taxId || "-"],
      ["Payment terms", c.paymentTerms],
    ],
    headStyles: { fillColor: accent },
    styles: { fontSize: 9, cellPadding: 5 },
    columnStyles: { 0: { fontStyle: "bold", cellWidth: 140 } },
  });

  autoTable(doc, {
    startY: after() + 20,
    margin: { left: margin, right: margin },
    head: [["Recent orders", "Placed (UTC)", "Status", "Value"]],
    body: c.recentOrders.length
      ? c.recentOrders.map((o) => [`${o.id}  ${o.title}`, o.placedAt.slice(0, 10), o.stageLabel, egp(o.amount)])
      : [["No orders yet", "", "", ""]],
    headStyles: { fillColor: accent },
    styles: { fontSize: 9, cellPadding: 5 },
    columnStyles: { 3: { halign: "right" } },
  });

  if (c.notes.length) {
    autoTable(doc, {
      startY: after() + 20,
      margin: { left: margin, right: margin },
      head: [["Administrative notes", "When (UTC)"]],
      body: c.notes.map((n) => [`${n.urgent ? "[URGENT] " : ""}${n.text}\n${n.author}`, n.at.slice(0, 16).replace("T", " ")]),
      headStyles: { fillColor: accent },
      styles: { fontSize: 9, cellPadding: 5 },
      columnStyles: { 1: { cellWidth: 100 } },
    });
  }

  doc.setFontSize(8).setTextColor(130);
  doc.text("Generated by PrintPro admin. Internal document.", margin, doc.internal.pageSize.getHeight() - 30);
  doc.save(`customer-${c.id}.pdf`);
};
